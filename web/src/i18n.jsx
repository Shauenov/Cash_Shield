const fill = (s, v) => (v ? s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? v[k] : m)) : s)
/** Text in a given language, falling back to English. */
export const tr = (lang, k, v) => fill(D[lang]?.[k] ?? D.en[k] ?? k, v)
/** t('key', { amount: '1 000 ₸' }) in the current language. */
export function useT() {
  const { lang } = useLang()
  return (k, v) => tr(lang, k, v)
}
